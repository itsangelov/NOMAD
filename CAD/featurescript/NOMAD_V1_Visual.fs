function f2(x is number) returns string
{
    var v = round(x * 100);
    var sg = "";
    if (v < 0)
    {
        sg = "-";
        v = -v;
    }
    const ip = floor(v / 100);
    const dp = v - ip * 100;
    var ds = "" ~ dp;
    if (dp < 10)
    {
        ds = "0" ~ dp;
    }
    return sg ~ ip ~ "." ~ ds;
}
