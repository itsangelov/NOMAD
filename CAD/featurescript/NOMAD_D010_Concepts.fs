function d010Cut(context is Context, id is Id, target is Query, boxes is array)
{
    var tools = [];
    for (var i = 0; i < size(boxes); i += 1)
        tools = append(tools, d010Box(context, id + ("t" ~ i), boxes[i]));
    opBoolean(context, id + "sub", { "tools" : qUnion(tools), "targets" : target, "operationType" : BooleanOperationType.SUBTRACTION });
}

function d010Rec(grp is map, frame is string, q is Query) returns map
{
    grp[frame] = append(grp[frame] == undefined ? [] : grp[frame], q);
    return grp;
}

// ================= kinematics (same conventions as d010_phase2_study.py) =================

function d010AxisRot(y is number, z is number, a is number) returns Transform
{
    return rotationAround(line(d010P(0, y, z), D010_X), a * degree);
}

// Frame transform: body point in the CLOSED / STOWED frame -> world (before the instance offset).
function d010FrameT(frame is string, ps is map) returns Transform
{
    const lid = d010AxisRot(D010.HAY, D010.HAZ, -ps.phi);
    if (frame == "base" || frame == "stay")
        return identityTransform();
    if (frame == "lid" || frame == "A_rail_R" || frame == "A_rail_L")
        return lid;
    if (frame == "leaf")
        return lid * d010AxisRot(D010.B1_AXIS_Y, D010.B1_AXIS_Z, ps.psi);
    const side = frame == "A_car_R" || frame == "A_loop_R" || frame == "A_cas_R" ? "R" : "L";
    const sg = side == "R" ? 1 : -1;
    const s = side == "R" ? ps.sR : ps.sL;
    const frac = (frame == "A_loop_R" || frame == "A_loop_L") ? 0.5 : 1;
    const slide = transform(d010P(sg * s * frac * D010.SOLAR_SLIDE_TRAVEL, 0, 0));
    if (frame == "A_cas_R" || frame == "A_cas_L")
        return lid * slide * d010AxisRot(side == "R" ? D010.HYR : D010.HYL, D010.HZ, side == "R" ? ps.tR : ps.tL);
    return lid * slide;
}

// ================= one NOMAD instance =================

// Builds one architecture in one pose, then moves it by `offset`. Returns key -> Query (for checks).
export function d010Instance(context is Context, id is Id, arch is string, ps is map, offset is Vector, label is string,
    tipWind is number, opts is map) returns map
{
    const pre = arch ~ " " ~ label ~ " | ";
    var grp = {};
    var parts = {};
    const W2 = D010.BODY_WIDTH / 2;
    const Dp = D010.BODY_DEPTH;
    const Hb = D010.BODY_HEIGHT;
    const WT = D010.WALL_THICKNESS;
    const ZF = D010.ZF;

    // ---------------- shared base reference (simplified shell + feet + envelopes) ----------------
    var sh = d010Box(context, id + "baseShell", [-W2, 0, 0, W2, Dp, Hb]);
    var kb = [];
    var tp = [];
    for (var i = 0; i < size(D010_BASE); i += 1)
    {
        if (D010_BASE[i][0] == "ENV_KEYBOARD")
            kb = D010_BASE[i][1][0];
        if (D010_BASE[i][0] == "ENV_TRACKPAD")
            tp = D010_BASE[i][1][0];
    }
    d010Cut(context, id + "baseCut", sh, [[-W2 + WT, WT, WT, W2 - WT, Dp - WT, Hb - WT],
                [kb[1], kb[2], Hb - WT - 1, kb[4], kb[5], Hb + 1], [tp[1], tp[2], Hb - WT - 1, tp[4], tp[5], Hb + 1]]);
    d010Name(context, sh, pre ~ "BASE_REF shell (simplified Round C V0.1; exact base = NOMAD E Base)", "baseShell");
    parts["base"] = sh;
    const fx = W2 - D010.FOOT_INSET;
    for (var i = 0; i < 4; i += 1)
    {
        const q = d010CylZ(context, id + ("foot" ~ i), (i % 2 == 0 ? -fx : fx), (i < 2 ? D010.FOOT_INSET : Dp - D010.FOOT_INSET), -D010.FOOT_H, 0, 6);
        d010Name(context, q, pre ~ "BASE_REF foot " ~ (i + 1) ~ " [ASSUMED 4 mm]", "feet");
    }
    for (var i = 0; i < size(D010_BASE); i += 1)
    {
        const nm = D010_BASE[i][0];
        const b = D010_BASE[i][1][0];
        const isKeep = nm == "KEEPOUT_PLUGS_MAIN" || nm == "KEEPOUT_PLUGS_AUX";
        const isInput = nm == "ENV_KEYBOARD" || nm == "ENV_TRACKPAD";
        if (nm == "BASE_SHELL" || (isKeep && !opts.env) || (!isKeep && !isInput && !opts.internals))
            continue;
        const q = d010Box(context, id + ("env" ~ i), [b[1], b[2], b[3], b[4], b[5], b[6]]);
        d010Name(context, q, pre ~ "BASE_REF " ~ nm, isKeep ? "keepout" : (isInput ? "input" : (nm == "ENV_BATTERY_BAY" ? "battery" : "electronics")));
        parts[nm] = q;
    }

    // ---------------- lid (closed frame) ----------------
    const T = arch == "A" ? D010.LID_THICKNESS : D010.B1_CORE;
    var lidShell = d010Box(context, id + "lidShell", [-W2, 0, ZF, W2, Dp, ZF + T]);
    var lidCuts = [[-D010.IX, D010.IY0, D010.ZFR, D010.IX, D010.IY1, arch == "A" ? D010.ZS0 : ZF + T - WT],
            [-D010.DX, D010.DY0, ZF - 1, D010.DX, D010.DY1, D010.ZFR + 0.01]];
    if (arch == "A")
    {
        for (var sgi = 0; sgi < 2; sgi += 1)
        {
            const sg = sgi == 0 ? 1 : -1;
            const rc = sgi == 0 ? D010.RCR : D010.RCL;
            const xa = sg > 0 ? D010.IX - 1 : -W2 - 1;
            lidCuts = append(lidCuts, [xa, D010.CY0 - 1, D010.ZC0 - 1, xa + WT + 2, D010.CY1 + 1, D010.ZC1 + 1]);
            lidCuts = append(lidCuts, [xa, rc - D010.BW2 - 1, D010.BZ0 - 1, xa + WT + 2, rc + D010.BW2 + 1, D010.ZC0]);
        }
    }
    d010Cut(context, id + "lidCut", lidShell, lidCuts);
    d010Name(context, lidShell, pre ~ (arch == "A" ? "LID class A 37.6 (frame + sandwich rear shell, side slots) [YAML working]" :
                "LID B1 core 19 (display, controller, thin shell) [EST]"), "lidShell");
    grp = d010Rec(grp, "lid", lidShell);
    parts["lidShell"] = lidShell;
    const disp = d010Box(context, id + "display", [-D010.DX, D010.DY0, D010.ZD0, D010.DX, D010.DY1, D010.ZD1]);
    d010Name(context, disp, pre ~ "DISPLAY 10.1 in envelope", "display");
    grp = d010Rec(grp, "lid", disp);
    if (opts.internals)
    {
        const ctl = d010Box(context, id + "ctl", [D010.CBX0, D010.CBY0, D010.ZFR, D010.CBX1, D010.IY1, D010.CBZ1]);
        d010Name(context, ctl, pre ~ "ENV_DISPLAY_CONTROLLER", "controller");
        grp = d010Rec(grp, "lid", ctl);
        parts["ctl"] = ctl;
    }
    const hb = d010CylX(context, id + "hingeBarrel", -D010.IX, D010.IX, D010.HAY, D010.HAZ, D010.HINGE_BARREL_DIAMETER / 2 * 0.6);
    d010Name(context, hb, pre ~ "DISPLAY HINGE AXIS (D-006; friction hinges TBD)", "steel");

    if (arch == "A")
        grp = d010BuildA(context, id + "A", pre, grp, opts);
    else
        grp = d010BuildB1(context, id + "B", pre, grp, ps, opts, lidShell);

    // ---------------- transforms per frame ----------------
    const frames = keys(grp);
    for (var i = 0; i < size(frames); i += 1)
    {
        opTransform(context, id + ("tx" ~ i), { "bodies" : qUnion(grp[frames[i]]), "transform" : d010FrameT(frames[i], ps) });
    }
    if (arch == "B1")
    {
        d010BuildStay(context, id + "stay", pre, ps.stay);
        parts["leafR"] = qCreatedBy(id + "B" + "frame0", EntityType.BODY);
        parts["leafL"] = qCreatedBy(id + "B" + "frame1", EntityType.BODY);
        parts["stayR"] = qCreatedBy(id + "stay" + "arm0", EntityType.BODY);
        parts["wm"] = qCreatedBy(id + "B" + "wm" + "inlay", EntityType.BODY);
        parts["wmPad"] = qCreatedBy(id + "B" + "wm" + "pad", EntityType.BODY);
    }
    else
    {
        parts["casR"] = qCreatedBy(id + "A" + "R" + "tray", EntityType.BODY);
        parts["bracketR"] = qCreatedBy(id + "A" + "R" + "bracket", EntityType.BODY);
    }

    // ---------------- cables (world, from the route anchors) ----------------
    if (opts.cables)
    {
        if (arch == "A")
        {
            d010Cable(context, id + "cR", pre ~ "CABLE A right", D010_ROUTE_A_R, ps, D010.CABLE_A_D, D010.CABLE_A_R);
            d010Cable(context, id + "cL", pre ~ "CABLE A left", D010_ROUTE_A_L, ps, D010.CABLE_A_D, D010.CABLE_A_R);
        }
        else
            d010Cable(context, id + "cB", pre ~ "CABLE B1", D010_ROUTE_B1, ps, D010.CABLE_B_D, D010.CABLE_B_R);
    }

    // ---------------- CG, plumb line, support polygon ----------------
    const cg = d010CG(arch, ps);
    parts["cg"] = cg;
    if (opts.cg)
        d010ShowCG(context, id + "cg", pre, arch, ps, cg, tipWind);

    opTransform(context, id + "offset", { "bodies" : qCreatedBy(id, EntityType.BODY), "transform" : transform(offset) });
    return parts;
}

// ---------------- Architecture A: rails, carriages, hub, index plate, S1-R stop envelope, cassettes ----------------
function d010BuildA(context is Context, id is Id, pre is string, grp0 is map, opts is map) returns map
{
    var grp = grp0;
    const hz = D010.HZ;
    const px0 = D010.GX0 + 0.5;
    const px1 = px0 + D010.SOLAR_INDEX_PLATE_THICKNESS;
    for (var k = 0; k < 2; k += 1)
    {
        const sd = k == 0 ? "R" : "L";
        const sg = k == 0 ? 1 : -1;
        const rc = k == 0 ? D010.RCR : D010.RCL;
        const hy = k == 0 ? D010.HYR : D010.HYL;
        const sid = id + sd;
        const xs = function(a is number, b is number) returns array
            {
                return sg > 0 ? [a, b] : [-b, -a];
            };
        // rail (C-channel with top slot), lid-fixed
        const rx = xs(D010.KX0, D010.RX1);
        var rail = d010Box(context, sid + "rail", [rx[0], rc - D010.RW2, D010.ZR0, rx[1], rc + D010.RW2, D010.ZR1]);
        d010Cut(context, sid + "railCut", rail, [[rx[0] - 1, rc - D010.RW2 + 2.5, D010.ZR0 + 2.5, rx[1] + 1, rc + D010.RW2 - 2.5, D010.ZR1 - 2.5],
                    [rx[0] - 1, rc - D010.SW2, D010.ZR1 - 3, rx[1] + 1, rc + D010.SW2, D010.ZR1 + 1]]);
        d010Name(context, rail, pre ~ "A" ~ sd ~ " RAIL (C-channel, structural) [B.1 V1 + fixes]", "rail");
        grp = d010Rec(grp, "lid", rail);
        // carriage + hub pin + index plate + S1-R stop envelope (slide with the carriage)
        const cx = xs(D010.KX0, D010.KX1);
        const car = d010Box(context, sid + "car", [cx[0], rc - D010.CW2 + 0.3, D010.ZR0 + 2.8, cx[1], rc + D010.CW2 - 0.3, D010.ZR1 - 2.8]);
        d010Name(context, car, pre ~ "A" ~ sd ~ " CARRIAGE", "carriage");
        grp = d010Rec(grp, "A_car_" ~ sd, car);
        const px = xs(D010.KX1 - 15, px1);
        const pin = d010CylX(context, sid + "pin", px[0], px[1], hy, hz, D010.SOLAR_HUB_PIN_DIAMETER / 2);
        d010Name(context, pin, pre ~ "A" ~ sd ~ " HUB PIN 5 mm (D-009 anti-rotation)", "steel");
        grp = d010Rec(grp, "A_car_" ~ sd, pin);
        const ipx = xs(px0, px1);
        const ip = d010CylX(context, sid + "index", ipx[0], ipx[1], hy, hz, D010.SOLAR_INDEX_PLATE_OUTER_RADIUS);
        d010Name(context, ip, pre ~ "A" ~ sd ~ " INDEX PLATE (D-009, 11 x 15 deg) [local candidate, not in production Onshape]", "steel");
        grp = d010Rec(grp, "A_car_" ~ sd, ip);
        const yx = xs(D010.KX1 + 1, D010.KX1 + 5);
        const yoke = d010CylX(context, sid + "yoke", yx[0], yx[1], hy, hz, 13);
        d010Name(context, yoke, pre ~ "A" ~ sd ~ " S1-R STOP YOKE ENVELOPE (+-80 deg; study only, not approved)", "stop");
        grp = d010Rec(grp, "A_car_" ~ sd, yoke);
        // cassette: bracket + tray + PV (slides and tilts)
        const bx = xs(D010.XI, D010.GX0);
        const br = d010Box(context, sid + "bracket", [bx[0], rc - D010.BW2, D010.BZ0, bx[1], rc + D010.BW2, D010.ZC0]);
        d010Name(context, br, pre ~ "A" ~ sd ~ " HUB BRACKET (PETG; below SF 2 at handling - OPEN)", "bracket");
        grp = d010Rec(grp, "A_cas_" ~ sd, br);
        const tx = xs(D010.XI, D010.XI + D010.SOLAR_CASSETTE_WIDTH);
        const tray = d010Box(context, sid + "tray", [tx[0], D010.CY0, D010.ZC0, tx[1], D010.CY1, D010.ZC1 - 1.5]);
        d010Name(context, tray, pre ~ "A" ~ sd ~ " CASSETTE TRAY 147.5 x 200", "tray");
        grp = d010Rec(grp, "A_cas_" ~ sd, tray);
        const vx = xs(D010.XI + 6, D010.XI + D010.SOLAR_CASSETTE_WIDTH - 6);
        const pv = d010Box(context, sid + "pv", [vx[0], D010.CY0 + 5, D010.ZC1 - 1.5, vx[1], D010.CY1 - 5, D010.ZC1]);
        d010Name(context, pv, pre ~ "A" ~ sd ~ " PV LAMINATE 135.5 x 190 (custom size, ASSUMED ~4.4 W)", "pv");
        grp = d010Rec(grp, "A_cas_" ~ sd, pv);
        if (opts.env)
        {
            const lx = xs(D010.LPX0, D010.LPX1);
            const ly = k == 0 ? [D010.LRY0, D010.LRY1] : [D010.LLY0, D010.LLY1];
            const band = d010Box(context, sid + "loopBand", [lx[0], ly[0], D010.ZR0, lx[1], ly[1], D010.ZR1]);
            d010Name(context, band, pre ~ "A" ~ sd ~ " KEEPOUT service-loop band (E2 reserve)", "reserve");
            grp = d010Rec(grp, "lid", band);
            // tilt envelope: +-75 deg sector about the hub axis over the deployed cassette span
            const ex = xs(D010.XI + D010.SOLAR_SLIDE_TRAVEL, D010.XI + D010.SOLAR_SLIDE_TRAVEL + D010.SOLAR_CASSETTE_WIDTH);
            const rLong = sqrt((hy - D010.CY0) ^ 2 + (D010.ZC1 - hz) ^ 2);
            const rShort = sqrt((D010.CY1 - hy) ^ 2 + (D010.ZC1 - hz) ^ 2);
            const e1 = d010Sector(context, sid + "tiltEnv1", ex[0], ex[1], hy, hz, k == 0 ? rShort : rLong, -75, 150);
            const e2 = d010Sector(context, sid + "tiltEnv2", ex[0], ex[1], hy, hz, k == 0 ? rLong : rShort, 105, 150);
            d010Name(context, qUnion([e1, e2]), pre ~ "A" ~ sd ~ " DEPLOYMENT ENVELOPE (slide out + tilt +-75)", "envelope");
            grp = d010Rec(grp, "lid", qUnion([e1, e2]));
        }
    }
    return grp;
}

// Cylinder sector about an X-parallel axis (y, z), radius r, from angle a0 (0 = +Y) over da degrees; x0..x1.
function d010Sector(context is Context, id is Id, x0 is number, x1 is number, y is number, z is number, r is number, a0 is number, da is number) returns Query
{
    const sk = newSketchOnPlane(context, id + "sk", { "sketchPlane" : plane(d010P(0, y, z), vector(0, 0, 1), D010_X) });
    skRectangle(sk, "r", { "firstCorner" : vector(x0, 0) * millimeter, "secondCorner" : vector(x1, r) * millimeter });
    skSolve(sk);
    opRevolve(context, id + "rev", { "entities" : qSketchRegion(id + "sk"), "axis" : line(d010P(0, y, z), D010_X), "angleForward" : da * degree });
    opDeleteBodies(context, id + "del", { "entities" : qCreatedBy(id + "sk") });
    const q = qCreatedBy(id + "rev", EntityType.BODY);
    opTransform(context, id + "rot", { "bodies" : q, "transform" : d010AxisRot(y, z, a0) });
    return q;
}

// ---------------- Architecture B1: foil, gap, leaf frame (2 halves), panel, hinges, knuckle, latch ----------------
function d010BuildB1(context is Context, id is Id, pre is string, grp0 is map, ps is map, opts is map, lidShell is Query) returns map
{
    var grp = grp0;
    const zc = D010.ZF + D010.B1_CORE;                  // lid back (core top)
    const z0 = D010.B1_Z_LEAF0;                         // panel back plane
    const zt = D010.ZF + D010.B1_LID_T;                 // leaf top
    const ay = D010.B1_AXIS_Y;
    const az = D010.B1_AXIS_Z;
    const lw = D010.B1_LEAF_W / 2;
    const Dp = D010.BODY_DEPTH;
    const px = D010.P108_X / 2;
    const py0 = (Dp - D010.P108_Y) / 2;
    var wmRect = undefined;
    if (opts.wm == true)
    {
        const w = d010Wordmark(context, id + "wm", pre, lidShell, zc);
        grp = d010Rec(grp, "lid", w.inlay);
        grp = d010Rec(grp, "lid", w.pad);
        wmRect = w.rect;
    }
    const foil = d010Box(context, id + "foil", [-135, 12, zc, 135, Dp - 12, zc + 0.3]);
    if (wmRect != undefined)
    {
        const m = D010_WM.margin;
        d010Cut(context, id + "foilWin", foil, [[wmRect[0] - m, wmRect[1] - m, zc - 1, wmRect[2] + m, wmRect[3] + m, zc + 1]]);
    }
    d010Name(context, foil, pre ~ "B1 LOW-E FOIL on the lid back (aluminium tape) [thermal recommendation]", "foil");
    grp = d010Rec(grp, "lid", foil);
    if (ps.psi < 1)
    {
        const gap = d010Box(context, id + "gap", [-px, py0, zc + 0.3, px, Dp - py0, z0]);
        d010Name(context, gap, pre ~ "B1 AIR GAP " ~ D010.B1_GAP ~ " mm (vented at both leaf ends)", "gap");
        grp = d010Rec(grp, "lid", gap);
    }
    // leaf frame halves (open back: panel rebate + front lip; vents at both ends; knuckle / hinge relief in the front bar)
    const hingeX = 55;
    for (var k = 0; k < 2; k += 1)
    {
        const sg = k == 0 ? 1 : -1;
        const xs = function(a is number, b is number) returns array
            {
                return sg > 0 ? [a, b] : [-b, -a];
            };
        const ox = xs(0.25, lw);
        var fr = d010Box(context, id + ("frame" ~ k), [ox[0], 0, zc, ox[1], Dp, zt]);
        const o1 = xs(-1, px - 2.5);
        const o2 = xs(-1, px + 0.5);
        const v1 = xs(-1, 30);
        const kn = xs(hingeX - 16, D010.B1_LEAF_W / 2 - 3);
        const v2 = xs(-1, 110);
        const rl = xs(-1, lw + 1);
        d010Cut(context, id + ("frameCut" ~ k), fr, [[o1[0], py0 + 3, zc - 1, o1[1], Dp - py0 - 3, zt + 1],
                    [o2[0], py0 - 0.5, zc - 1, o2[1], Dp - py0 + 0.5, z0 + D010.P108_T],
