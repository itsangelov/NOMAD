        grp = d010Rec(grp, "lid", e);
    }
    return grp;
}

// NOMAD wordmark: text sketched on the recess floor (x along -X, up along -Y so it reads upright from behind the open
// lid), extruded as a cutting tool through the back skin and as a 0.2 mm contrasting floor inlay, centred on the lid
// centreline at y = yc, then cut into the lid shell. Returns the inlay part, the internal backing pad and the text rectangle.
// Only the glyph (outer) regions are extruded: qSketchRegion(.., true) drops the letter counters (O, A, D), which the
// unfiltered query would fill. Never name a variable or map key `box`: it is a FeatureScript reserved word (parse error).
function d010Wordmark(context is Context, id is Id, pre is string, lidShell is Query, zc is number) returns map
{
    const h = D010_WM.height;
    const dp = D010_WM.depth;
    const sk = newSketchOnPlane(context, id + "sk", { "sketchPlane" : plane(d010P(0, 0, zc - dp), vector(0, 0, 1), -D010_X) });
    skText(sk, "t", { "text" : D010_WM.text, "fontName" : D010_WM.font, "firstCorner" : vector(0, 0) * millimeter,
                "secondCorner" : vector(10, h) * millimeter });
    skSolve(sk);
    opExtrude(context, id + "tool", { "entities" : qSketchRegion(id + "sk", true), "direction" : vector(0, 0, 1),
                "endBound" : BoundingType.BLIND, "endDepth" : (dp + 0.5) * millimeter });
    opExtrude(context, id + "inlay", { "entities" : qSketchRegion(id + "sk", true), "direction" : vector(0, 0, 1),
                "endBound" : BoundingType.BLIND, "endDepth" : 0.2 * millimeter });
    opDeleteBodies(context, id + "skd", { "entities" : qCreatedBy(id + "sk") });
    const tool = qCreatedBy(id + "tool", EntityType.BODY);
    const inlay = qCreatedBy(id + "inlay", EntityType.BODY);
    const bb = evBox3d(context, { "topology" : tool });
    const dx = -(bb.minCorner[0] + bb.maxCorner[0]) / 2;
    const dy = D010_WM.yc * millimeter - (bb.minCorner[1] + bb.maxCorner[1]) / 2;
    opTransform(context, id + "ctr", { "bodies" : qUnion([tool, inlay]), "transform" : transform(vector(dx, dy, 0 * millimeter)) });
    const rect = [(bb.minCorner[0] + dx) / millimeter, (bb.minCorner[1] + dy) / millimeter, (bb.maxCorner[0] + dx) / millimeter,
            (bb.maxCorner[1] + dy) / millimeter];
    opBoolean(context, id + "cut", { "tools" : tool, "targets" : lidShell, "operationType" : BooleanOperationType.SUBTRACTION });
    d010Name(context, inlay, pre ~ "D010_NOMAD_Wordmark (recessed " ~ dp ~ " mm, cap height " ~ h ~ " mm, " ~ roundToPrecision(rect[2] - rect[0], 1) ~
                " mm wide; font Michroma = FALLBACK for Eurostile Extended, not final identity)", "wordmark");
    const zs = D010.ZF + D010.B1_CORE - D010.WALL_THICKNESS;
    const pad = d010Box(context, id + "pad", [rect[0] - 2, rect[1] - 2, zs - D010_WM.pad, rect[2] + 2, rect[3] + 2, zs]);
    d010Name(context, pad, pre ~ "D010_NOMAD_Wordmark backing pad (+" ~ D010_WM.pad ~ " mm inside the back skin, keeps 2.5 mm under the recess)", "wmPad");
    return { "inlay" : inlay, "pad" : pad, "rect" : rect };
}

// Rear outrigger stay: 2 stainless flats pivoting on vertical M4 shoulder screws in the base rear corners.
function d010BuildStay(context is Context, id is Id, pre is string, deployed is boolean)
{
    const x = D010.STAY_X;
    const y0 = D010.STAY_Y0;
    const hb = D010.STAY_B / 2;
    const z0 = -D010.FOOT_H + 0.5;
    const z1 = z0 + D010.STAY_T;
    for (var k = 0; k < 2; k += 1)
    {
        const sg = k == 0 ? 1 : -1;
        var c;
        if (deployed)
            c = [sg * x - hb, y0 - D010.STAY_ROOT, z0, sg * x + hb, y0 + D010.STAY_L, z1];
        else
            c = [sg * x - hb, y0 - D010.STAY_L, z0, sg * x + hb, y0 + D010.STAY_ROOT, z1];
        const arm = d010Box(context, id + ("arm" ~ k), c);
        d010Name(context, arm, pre ~ "B1 STAY ARM " ~ (k == 0 ? "R" : "L") ~ " 3 x 16 stainless (" ~ (deployed ? "DEPLOYED rearward" :
                    "stowed forward under the base") ~ ")", "stay");
        const pin = d010CylZ(context, id + ("pivot" ~ k), sg * x, y0, -D010.FOOT_H, 8, 2);
        d010Name(context, pin, pre ~ "B1 STAY PIVOT M4 shoulder screw " ~ (k == 0 ? "R" : "L"), "steel");
        if (deployed)
        {
            const pad = d010CylZ(context, id + ("pad" ~ k), sg * x, y0 + D010.STAY_L - hb, -D010.FOOT_H, z0, hb);
            d010Name(context, pad, pre ~ "B1 STAY FOOT PAD " ~ (k == 0 ? "R" : "L"), "feet");
        }
    }
}

// ---------------- cables: filleted polyline tubes; special (moving) segments as separate coloured parts ----------------
function d010Cable(context is Context, id is Id, name is string, route is array, ps is map, d is number, R is number)
{
    var pts = [];
    var tags = [];
    for (var i = 0; i < size(route); i += 1)
    {
        pts = append(pts, d010FrameT(route[i][0], ps) * d010P(route[i][1][0], route[i][1][1], route[i][1][2]));
        tags = append(tags, route[i][2]);
    }
    const n = size(pts);
    const r = d / 2 * millimeter;
    var tl = makeArray(n, 0 * millimeter);
    var info = makeArray(n, undefined);
    var rmin = R;
    for (var i = 1; i < n - 1; i += 1)
    {
        const v1 = pts[i] - pts[i - 1];
        const v2 = pts[i + 1] - pts[i];
        const l1 = norm(v1);
        const l2 = norm(v2);
        if (l1 < 1e-6 * millimeter || l2 < 1e-6 * millimeter)
            continue;
        const u1 = v1 / l1;
        const u2 = v2 / l2;
        const c = max(-1, min(1, dot(u1, u2)));
        const th = acos(c);
        if (th < 0.5 * degree)
            continue;
        const tmax = min(l1 * (i == 1 ? 1 : 0.5), l2 * (i == n - 2 ? 1 : 0.5));
        var t = R * millimeter * tan(th / 2);
        var re = R * millimeter;
        if (t > tmax)
        {
            t = tmax;
            re = t / tan(th / 2);
        }
        rmin = min(rmin, re / millimeter);
        tl[i] = t;
        info[i] = { "u1" : u1, "u2" : u2, "th" : th, "re" : re, "t" : t };
    }
    var groups = {};
    for (var i = 0; i < n - 1; i += 1)
    {
        const u = normalize(pts[i + 1] - pts[i]);
        const a = pts[i] + u * tl[i];
        const b = pts[i + 1] - u * tl[i + 1];
        const key = tags[i] == "" ? "static" : tags[i];
        if (norm(b - a) > 0.05 * millimeter)
        {
            fCylinder(context, id + ("s" ~ i), { "bottomCenter" : a, "topCenter" : b, "radius" : r });
            groups[key] = append(groups[key] == undefined ? [] : groups[key], qCreatedBy(id + ("s" ~ i), EntityType.BODY));
        }
    }
    for (var i = 1; i < n - 1; i += 1)
    {
        if (info[i] == undefined)
            continue;
        const f = info[i];
        const t1 = pts[i] - f.u1 * f.t;
        const nrm = normalize(f.u2 - f.u1 * dot(f.u1, f.u2));
        const ctr = t1 + nrm * f.re;
        const ax = normalize(cross(f.u1, f.u2));
        const sk = newSketchOnPlane(context, id + ("ak" ~ i), { "sketchPlane" : plane(t1, f.u1) });
        skCircle(sk, "c", { "center" : vector(0, 0) * millimeter, "radius" : r });
        skSolve(sk);
        try silent
        {
            opRevolve(context, id + ("a" ~ i), { "entities" : qSketchRegion(id + ("ak" ~ i)), "axis" : line(ctr, ax), "angleForward" : f.th });
            const key = (tags[i - 1] == "loop" && tags[i] == "loop") ? "loop" : "static";
            groups[key] = append(groups[key] == undefined ? [] : groups[key], qCreatedBy(id + ("a" ~ i), EntityType.BODY));
        }
        opDeleteBodies(context, id + ("ad" ~ i), { "entities" : qCreatedBy(id + ("ak" ~ i)) });
    }
    const labels = { "static" : ["", "cable"], "twist" : [" AXIAL TWIST ZONE (hinge crossing)", "twist"],
            "loop" : [" ROLLING SERVICE LOOP (R20, moving)", "loop"], "sbend" : [" HUB-LINK S-BEND (+-80 deg tilt, R < 6d)", "sbend"],
            "hop" : [" CARRIAGE->LOOP TRANSITION through the rail wall - UNRESOLVED", "hop"] };
    const gk = keys(groups);
    for (var g = 0; g < size(gk); g += 1)
    {
        const q = qUnion(groups[gk[g]]);
        if (size(groups[gk[g]]) > 1)
        {
            try silent
            {
                opBoolean(context, id + ("u" ~ g), { "tools" : q, "operationType" : BooleanOperationType.UNION });
            }
        }
        const lab = labels[gk[g]];
        d010Name(context, q, name ~ lab[0] ~ " d " ~ d ~ " mm" ~ (gk[g] == "static" ? " (smallest drawn bend R " ~ roundToPrecision(rmin, 1) ~ ")" : ""), lab[1]);
    }
    const pe = pts[n - 1];
    fCuboid(context, id + "pe", { "corner1" : pe - vector(6, 0, 4) * millimeter, "corner2" : pe + vector(6, 5, 4) * millimeter });
    d010Name(context, qCreatedBy(id + "pe", EntityType.BODY), name ~ " CONNECTOR at power electronics (MPPT input)", "connector");
}

// ---------------- CG ----------------
export function d010CG(arch is string, ps is map) returns Vector
{
    const lst = arch == "A" ? D010_MASS_A : D010_MASS_B1;
    var m = 0;
    var s = vector(0, 0, 0) * millimeter;
    for (var i = 0; i < size(lst); i += 1)
    {
        const it = lst[i];
        var p = d010P(it[3][0], it[3][1], it[3][2]);
        if (it[2] == "stay" && ps.stay)
            p = p + vector(0, D010.STAY_L / 2, 0) * millimeter;
        p = d010FrameT(it[2], ps) * p;
        m += it[1];
        s = s + p * it[1];
    }
    return s / m;
}

function d010ShowCG(context is Context, id is Id, pre is string, arch is string, ps is map, cg is Vector, tipWind is number)
{
    const zt = -D010.FOOT_H;
    const xi = D010.BODY_WIDTH / 2 - D010.FOOT_INSET;
    const y0 = D010.FOOT_INSET;
    const y1 = D010.BODY_DEPTH - D010.FOOT_INSET;
    var poly = [vector(-xi, y0), vector(xi, y0), vector(xi, y1)];
    var rear = y1;
    if (arch == "B1" && ps.stay)
    {
        const yf = D010.STAY_Y0 + D010.STAY_L;
        poly = concatenateArrays([poly, [vector(D010.STAY_X, yf), vector(-D010.STAY_X, yf)]]);
        rear = yf;
    }
    poly = concatenateArrays([poly, [vector(-xi, y1), vector(-xi, y0)]]);
    var pp = [];
    for (var i = 0; i < size(poly); i += 1)
        pp = append(pp, poly[i] * millimeter);
    const sk = newSketchOnPlane(context, id + "sk", { "sketchPlane" : plane(vector(0, 0, zt - 0.6) * millimeter, vector(0, 0, 1), D010_X) });
    skPolyline(sk, "p", { "points" : pp });
    skSolve(sk);
    opExtrude(context, id + "poly", { "entities" : qSketchRegion(id + "sk"), "direction" : vector(0, 0, 1),
                "endBound" : BoundingType.BLIND, "endDepth" : 0.5 * millimeter });
    opDeleteBodies(context, id + "skd", { "entities" : qCreatedBy(id + "sk") });
    const c = cg / millimeter;
    const margin = rear - c[1];
    d010Name(context, qCreatedBy(id + "poly", EntityType.BODY), pre ~ "SUPPORT POLYGON (feet" ~ (arch == "B1" && ps.stay ? " + stay feet" : "") ~
            "; rear line y " ~ roundToPrecision(rear, 1) ~ ")", "support");
    fCuboid(context, id + "ball", { "corner1" : cg - vector(6, 6, 6) * millimeter, "corner2" : cg + vector(6, 6, 6) * millimeter });
    const txt = "CG x " ~ roundToPrecision(c[0], 1) ~ " y " ~ roundToPrecision(c[1], 1) ~ " z " ~ roundToPrecision(c[2], 1) ~
        " | rear margin " ~ roundToPrecision(margin, 1) ~ " mm" ~ (tipWind > 0 ? " | calc rear tip wind " ~ tipWind ~ " m/s" : "");
    d010Name(context, qCreatedBy(id + "ball", EntityType.BODY), pre ~ txt, "cg");
    fCylinder(context, id + "plumb", { "bottomCenter" : vector(c[0], c[1], zt) * millimeter, "topCenter" : cg, "radius" : 0.8 * millimeter });
    d010Name(context, qCreatedBy(id + "plumb", EntityType.BODY), pre ~ "CG plumb line", "cg");
}
