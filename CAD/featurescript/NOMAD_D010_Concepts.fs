function d010StateIndex(s is D010State) returns number
{
    const order = [D010State.STOWED, D010State.DISPLAY_OPEN, D010State.PARTIAL, D010State.NORMAL, D010State.MAX, D010State.SPECIAL];
    for (var i = 0; i < 6; i += 1)
        if (order[i] == s)
            return i;
    return -1;
}

function d010StatePose(e is array) returns map
{
    return { "phi" : e[1], "sR" : e[2], "tR" : e[3], "sL" : e[4], "tL" : e[5], "psi" : e[6], "stay" : e[7] };
}

