function d010P(x is number, y is number, z is number) returns Vector
{
    return vector(x, y, z) * millimeter;
}

function d010Box(context is Context, id is Id, c is array) returns Query
{
    fCuboid(context, id, { "corner1" : d010P(c[0], c[1], c[2]), "corner2" : d010P(c[3], c[4], c[5]) });
